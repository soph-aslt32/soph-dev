#Requires -Version 5.1
# =============================================================================
# Scripts.ps1 — 開発環境ごとの Windows 側のスクリプト（envs\<名前>\ の Code-<名前>.cmd、LocalGit の Sync-<名前>.ps1・.cmd）を作る
#
# Common.ps1・Base.ps1 を先に dot-source しておく（$script:ToolRoot・$script:DevcontainerCli を使う）。
# 決まっていること: DESIGN.md の 6.4（D35）、7.2、D17。同期スクリプトのひな形は templates\Sync-Env.ps1.tmpl。
# =============================================================================

# 開発環境ごとの Windows 側のスクリプトを置くフォルダ（ツールのフォルダの envs\<名前>。.gitignore で git の対象から外してある）
function Get-EnvScriptDir([string]$EnvName) {
    return (Join-Path (Join-Path $script:ToolRoot 'envs') $EnvName)
}

# 文字列を、PowerShell の単一引用符の文字列の中身として書けるようにする（' のほか、’ などの別の形の引用符も 2 つ重ねる）
function ConvertTo-SingleQuotedContent([string]$Text) {
    return [System.Management.Automation.Language.CodeGeneration]::EscapeSingleQuotedStringContent($Text)
}

# ひな形から、この開発環境の同期スクリプト（Sync-<名前>.ps1）の中身を作る。
# 印（__ENV_NAME__ など）は 1 回の置き換えで値にする（値の中に印の形の文字があっても、もう一度置き換えない）
function New-SyncScriptText([string]$EnvName, [string]$RepoPath, [string]$GeneratedAt) {
    $template = [System.IO.File]::ReadAllText((Join-Path $script:ToolRoot 'templates\Sync-Env.ps1.tmpl'), [System.Text.Encoding]::UTF8)
    $values = @{
        '__ENV_NAME__'         = $EnvName
        '__REPO_PATH__'        = $RepoPath
        '__GENERATED_AT__'     = $GeneratedAt
        '__DEVCONTAINER_CLI__' = $script:DevcontainerCli
    }
    $unknown = @([regex]::Matches($template, '__[A-Z_]+__') | ForEach-Object { $_.Value } | Where-Object { -not $values.ContainsKey($_) } | Sort-Object -Unique)
    if ($unknown.Count -gt 0) {
        Stop-Setup "同期スクリプトのひな形に、知らない印があります: $($unknown -join ', ')" @('ツールのフォルダの templates\Sync-Env.ps1.tmpl を確かめてください。')
    }
    $evaluator = {
        param($m)
        return [System.Management.Automation.Language.CodeGeneration]::EscapeSingleQuotedStringContent($values[$m.Value])
    }.GetNewClosure()
    return [regex]::Replace($template, '__(ENV_NAME|REPO_PATH|GENERATED_AT|DEVCONTAINER_CLI)__', [System.Text.RegularExpressions.MatchEvaluator]$evaluator)
}

# Code-<名前>.cmd の行（ASCII だけ。cmd.exe はバッチファイルをコンソールのコードページで読むため）。
# 土台の config\ を WSL のウィンドウで開くところまでを行い、「Reopen in Container」は利用者が押す（D35）。
# code コマンド（code.cmd → cli.js）は通さず、code.cmd の 1 つ上の Code.exe を、code コマンドと同じ引数・環境変数で start する。
# code コマンドから開くと、新しく立ち上がった VS Code の本体がこの窓のコンソールを受け継ぎ、VS Code をすべて閉じるまで窓が閉じない
function New-CodeCmdLines([string]$EnvName) {
    $p = "/home/dcs/envs/$EnvName/config"
    return @(
        '@echo off',
        "rem Code-$EnvName.cmd - opens the dev environment `"$EnvName`" in VS Code (dev-container-setup).",
        "rem It opens $p in the WSL distribution dcs-base. Then choose `"Reopen in Container`".",
        'rem Generated by dev-container-setup. Keep this file ASCII-only with CRLF line endings:',
        'rem cmd.exe reads batch files in the console code page.',
        'rem Code.exe is started directly, with the arguments and environment that the code command gives it.',
        'rem Through the code command, a newly started VS Code keeps this console, so this window stays open.',
        'setlocal',
        'set "CODEBIN="',
        'for /f "delims=" %%I in (''where code.cmd 2^>nul'') do if not defined CODEBIN set "CODEBIN=%%~dpI"',
        'if not defined CODEBIN goto nocode',
        'if not exist "%CODEBIN%..\Code.exe" goto nocode',
        'set "VSCODE_DEV="',
        'set "ELECTRON_RUN_AS_NODE="',
        'set "ELECTRON_NO_ATTACH_CONSOLE=1"',
        "start `"`" `"%CODEBIN%..\Code.exe`" --remote wsl+dcs-base $p",
        'if errorlevel 1 goto failed',
        'exit /b 0',
        ':nocode',
        'echo VS Code was not found (the code command, and Code.exe in the folder above it).',
        'echo Install VS Code, and make sure "Add to PATH" is selected in the installer.',
        'pause',
        'exit /b 1',
        ':failed',
        'echo VS Code could not be started. Read the messages above.',
        'pause',
        'exit /b 1')
}

# cmd.exe はバッチファイルをコンソールのコードページで読むので、.cmd は ASCII の文字だけ・改行は CRLF にする
function Write-AsciiCmd([string]$Path, [string[]]$Lines) {
    $text = ($Lines -join "`r`n") + "`r`n"
    if ($text -match '[^\x00-\x7F]') { Stop-Setup "$Path に ASCII でない文字が入ります。" @('ツールの不具合です。') }
    [System.IO.File]::WriteAllText($Path, $text, [System.Text.Encoding]::ASCII)
}

# 開発環境ごとの Windows 側のスクリプトを、envs\<名前>\ に書く（あれば書き直す）。
# Code-<名前>.cmd はいつも、Sync-<名前>.ps1・Sync-<名前>.cmd は LocalGit のときだけ
function Write-EnvScripts([string]$EnvName, [string]$Mode, [string]$RepoPath) {
    $dir = Get-EnvScriptDir $EnvName
    Write-Step "開発環境ごとの Windows 側のスクリプトを作ります（$dir）"
    if ($script:DryRun) {
        Write-DryRun "Code-$EnvName.cmd を作る"
        if ($Mode -eq 'LocalGit') { Write-DryRun "Sync-$EnvName.ps1 と Sync-$EnvName.cmd を作る" }
        return
    }
    $null = New-Item -ItemType Directory -Path $dir -Force
    Write-AsciiCmd (Join-Path $dir "Code-$EnvName.cmd") (New-CodeCmdLines $EnvName)
    Write-Ok "VS Code で開くスクリプトを作りました: Code-$EnvName.cmd"
    if ($Mode -ne 'LocalGit') { return }

    $name = "Sync-$EnvName"
    $text = (New-SyncScriptText $EnvName $RepoPath (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) -replace "`r`n", "`n" -replace "`n", "`r`n"
    # Windows PowerShell 5.1 が日本語を正しく読めるよう、BOM 付きの UTF-8・CRLF で書く
    [System.IO.File]::WriteAllText((Join-Path $dir "$name.ps1"), $text, (New-Object System.Text.UTF8Encoding($true)))
    Write-AsciiCmd (Join-Path $dir "$name.cmd") @(
        '@echo off',
        "rem $name.cmd - runs $name.ps1 in this folder (LocalGit sync for the dev environment `"$EnvName`").",
        "rem Keep $name.cmd and $name.ps1 together in the same folder; the folder itself can be anywhere.",
        'rem Generated by dev-container-setup. Arguments are passed to the .ps1 as they are.',
        'setlocal',
        "powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"%~dp0$name.ps1`" %*",
        'set "RC=%ERRORLEVEL%"',
        'echo.',
        'rem Keep the window open when started by double-click.',
        'pause',
        'exit /b %RC%')
    Write-Ok "同期スクリプトを作りました: $name.ps1、$name.cmd"
}

# 前回この開発環境のために作った同期スクリプト（envs\<名前>\Sync-<名前>.ps1）に書かれている、Windows 側の bare リポジトリの場所。
# 無い・読めないときは空文字列（やり直しのときの既定値に使うだけ）。PowerShell の構文解析で、$RepoPath = '...' の値を読む
function Get-PreviousRepoPath([string]$EnvName) {
    $ps1 = Join-Path (Get-EnvScriptDir $EnvName) "Sync-$EnvName.ps1"
    if (-not (Test-Path -LiteralPath $ps1 -PathType Leaf)) { return '' }
    try {
        $errors = $null
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($ps1, [ref]$null, [ref]$errors)
    } catch {
        return ''
    }
    $a = $ast.Find({
        param($n)
        $n -is [System.Management.Automation.Language.AssignmentStatementAst] -and $n.Left.Extent.Text -eq '$RepoPath'
    }, $true)
    if ($null -eq $a -or $a.Right -isnot [System.Management.Automation.Language.CommandExpressionAst]) { return '' }
    $v = $a.Right.Expression
    if ($v -isnot [System.Management.Automation.Language.StringConstantExpressionAst]) { return '' }
    return $v.Value
}
